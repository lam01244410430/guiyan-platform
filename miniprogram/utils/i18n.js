var LANGS = [
  { code: 'zh', label: '中文' },
  { code: 'vi', label: 'Tiếng Việt' },
  { code: 'en', label: 'English' }
];

function getLang() {
  try {
    var l = wx.getStorageSync('guiyan-lang');
    if (l === 'zh' || l === 'vi' || l === 'en') return l;
  } catch (e) {}
  return 'zh';
}

function setLang(code) {
  try { wx.setStorageSync('guiyan-lang', code); } catch (e) {}
  var app = getApp();
  if (app) app.globalData.lang = code;
}

function langIndex() {
  var l = getLang();
  for (var i = 0; i < LANGS.length; i++) if (LANGS[i].code === l) return i;
  return 0;
}

function t(key, lang) {
  var l = lang || getLang();
  if (STR[l] && STR[l][key] !== undefined) return STR[l][key];
  if (STR.zh[key] !== undefined) return STR.zh[key];
  return key;
}

function fmt(s, o) {
  return String(s).replace(/\{(\w+)\}/g, function (m, k) {
    return o[k] != null ? o[k] : m;
  });
}

module.exports = { STR: STR, LANGS: LANGS, getLang: getLang, setLang: setLang, langIndex: langIndex, t: t, fmt: fmt };
